"""Dataset loading and validation for the Phase 7 evaluation harness.

The dataset (``dataset.json``) is a version-controlled, hand-written set of
questions grounded in the two real corpus documents. Ground truth was checked
against the extracted page text of those PDFs; it is never generated by the
LLM under evaluation.

Relevance is judged by normalized substring matching: a retrieved chunk is
relevant to a question when at least one ``supporting_text`` fragment appears
inside the chunk's text. ``relevant_documents`` drives document-level recall.
"""

from __future__ import annotations

import json
import re
import unicodedata
from pathlib import Path

DATASET_PATH = Path(__file__).resolve().parent / "dataset.json"
CORPUS_DIR = Path(__file__).resolve().parent / "corpus"

_RE_WS = re.compile(r"\s+")
_RE_PUNCT = re.compile(r"[^\w\s]")


def normalize(text: str | None) -> str:
    """Fold text for fuzzy matching: lowercase, strip punctuation/case/wspaces."""
    if not text:
        return ""
    text = unicodedata.normalize("NFKC", text)
    text = _RE_PUNCT.sub(" ", text)
    text = _RE_WS.sub(" ", text)
    return text.strip().lower()


def chunk_is_relevant(chunk_text: str, supporting_text: list[str] | None) -> bool:
    """True when a normalized ground-truth fragment occurs in the chunk text."""
    if not supporting_text:
        return False
    norm_chunk = normalize(chunk_text)
    return any(normalize(fragment) in norm_chunk for fragment in supporting_text)


class Question:
    """A single evaluation item with its hand-verified ground truth."""

    __slots__ = (
        "id",
        "question",
        "expected_answer",
        "expected_answer_terms",
        "relevant_documents",
        "relevant_pages",
        "supporting_text",
        "category",
        "difficulty",
        "answerable",
    )

    def __init__(self, raw: dict) -> None:
        self.id = raw["id"]
        self.question = raw["question"]
        self.expected_answer = raw.get("expected_answer")
        self.expected_answer_terms = raw.get("expected_answer_terms", [])
        self.relevant_documents = raw.get("relevant_documents", [])
        self.relevant_pages = raw.get("relevant_pages", [])
        self.supporting_text = raw.get("supporting_text")
        self.category = raw.get("category", "other")
        self.difficulty = raw.get("difficulty", "medium")
        self.answerable = bool(raw.get("answerable", False))

    def as_dict(self) -> dict:
        return {
            "id": self.id,
            "question": self.question,
            "expected_answer": self.expected_answer,
            "expected_answer_terms": self.expected_answer_terms,
            "relevant_documents": self.relevant_documents,
            "relevant_pages": self.relevant_pages,
            "supporting_text": self.supporting_text,
            "category": self.category,
            "difficulty": self.difficulty,
            "answerable": self.answerable,
        }


class Dataset:
    """Loaded evaluation dataset plus its metadata."""

    def __init__(self, raw: dict) -> None:
        self.dataset_version = raw.get("dataset_version", "unknown")
        self.description = raw.get("description", "")
        self.corpus = raw.get("corpus", [])
        self.questions = [Question(q) for q in raw["questions"]]

    @property
    def answerable(self) -> list[Question]:
        return [q for q in self.questions if q.answerable]

    @property
    def unanswerable(self) -> list[Question]:
        return [q for q in self.questions if not q.answerable]

    @property
    def categories(self) -> list[str]:
        seen: list[str] = []
        for q in self.questions:
            if q.category not in seen:
                seen.append(q.category)
        return seen


def load_dataset(path: str | Path | None = None) -> Dataset:
    """Load and validate the evaluation dataset from disk."""
    dataset_file = Path(path) if path else DATASET_PATH
    if not dataset_file.is_file():
        raise FileNotFoundError(f"Dataset file not found: {dataset_file}")
    raw = json.loads(dataset_file.read_text(encoding="utf-8"))
    validate(raw)
    return Dataset(raw)


def validate(raw: dict) -> None:
    """Structural validation of a raw dataset payload.

    Raises ``ValueError`` on duplicate ids, empty questions or answerable items
    that lack a ground-truth answer / relevance anchors. Used by unit tests and
    by the runner before a run starts.
    """
    if "questions" not in raw or not isinstance(raw["questions"], list):
        raise ValueError("dataset must contain a non-empty 'questions' list")

    seen: set[str] = set()
    for item in raw["questions"]:
        qid = item.get("id")
        if not qid:
            raise ValueError("every question must have an 'id'")
        if qid in seen:
            raise ValueError(f"duplicate question id: {qid}")
        seen.add(qid)

        if not item.get("question", "").strip():
            raise ValueError(f"question {qid} has an empty prompt")

        answerable = bool(item.get("answerable", False))
        if answerable:
            if not item.get("relevant_documents"):
                raise ValueError(f"answerable question {qid} needs relevant_documents")
            if not item.get("supporting_text"):
                raise ValueError(f"answerable question {qid} needs supporting_text")
            if not item.get("expected_answer_terms"):
                raise ValueError(f"answerable question {qid} needs expected_answer_terms")
        else:
            if item.get("expected_answer") is not None:
                raise ValueError(
                    f"unanswerable question {qid} must have expected_answer == null"
                )